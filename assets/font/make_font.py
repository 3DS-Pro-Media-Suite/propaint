"""Reads Quicksand-Bold.ttf (next to this file) and writes source/data/font.h: two anti-aliased bitmap fonts for the UI.

Quicksand is under the SIL Open Font License, see OFL.txt in the repo root.
Run: python assets/font/make_font.py   (needs Pillow)
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "Quicksand-Bold.ttf")
OUT = os.path.join(HERE, "..", "..", "source", "data", "font.h")
SIZES = (("SMALL", 11), ("LARGE", 15))  # the name in the header and the pixel size
FIRST_CHAR, END_CHAR = 32, 127  # printable ASCII


def main():
    out = ["// The UI font (Quicksand Bold) as bitmaps. Generated by assets/font/make_font.py. Do not edit.\n",
           "#pragma once\n",
           "// clang-format off\n",
           f"#define FONT_GLYPH_COUNT {END_CHAR - FIRST_CHAR} // the printable ASCII characters, from the space\n"]
    for name, size in SIZES:
        font = ImageFont.truetype(TTF, size)
        ascent, descent = font.getmetrics()
        cell_w, cell_h = size + 4, ascent + descent + 2
        advances, glyphs = [], []
        for c in range(FIRST_CHAR, END_CHAR):
            im = Image.new("L", (cell_w, cell_h), 0)
            ImageDraw.Draw(im).text((1, ascent), chr(c), font=font, anchor="ls", fill=255)
            advances.append(int(round(font.getlength(chr(c)))) + 1)
            glyphs.append(list(im.getdata()))
        out.append(f"#define FONT_{name}_WIDTH {cell_w}\n#define FONT_{name}_HEIGHT {cell_h}\n")
        out.append(f"static const unsigned char FONT_{name}_ADVANCES[FONT_GLYPH_COUNT] = "
                   f"{{{','.join(map(str, advances))}}};\n")
        out.append(f"static const unsigned char FONT_{name}_GLYPHS[FONT_GLYPH_COUNT]"
                   f"[FONT_{name}_WIDTH * FONT_{name}_HEIGHT] = {{\n")
        for g in glyphs:
            out.append("{" + ",".join(map(str, g)) + "},\n")
        out.append("};\n")
    out.append("// clang-format on\n")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("".join(out))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
