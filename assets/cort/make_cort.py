"""Reads cort_atlas.png and cort_anims.json (next to this file) and writes source/data/cort.h.

The atlas and the json come from the mascot repo (mascot_out.py), which copies them here when it runs.
Run: python assets/cort/make_cort.py   (needs Pillow)
"""
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ATLAS = os.path.join(HERE, "cort_atlas.png")
ANIMS = os.path.join(HERE, "cort_anims.json")
OUT = os.path.join(HERE, "..", "..", "source", "data", "cort.h")


def read_strips():
    """{name: ([32x32 RGBA frames], [ms per frame], loops)}, one atlas row per animation, in the json's order."""
    atlas = Image.open(ATLAS).convert("RGBA")
    with open(ANIMS) as fh:
        meta = json.load(fh)
    w, h = meta["frame_w"], meta["frame_h"]
    strips = {}
    for name, anim in meta["anims"].items():
        y = anim["row"] * h
        frames = [atlas.crop((i * w, y, i * w + w, y + h)) for i in range(anim["frames"])]
        strips[name] = (frames, anim["ms"], anim["loop"])
    return strips, w, h


def write_header(strips, w, h):
    """Palette-indexed frames (0 = transparent) and the animation table. Palette entries are 0xAARRGGBB, with
    partial alpha where sub-pixel edges blend."""
    pal, frames, rows = [None], [], []
    for name, (imgs, ms, loop) in strips.items():
        rows.append((name, len(frames), len(imgs), loop, ms))
        for im in imgs:
            idx = []
            for c in im.getdata():
                if c[3] == 0:
                    idx.append(0)
                    continue
                if c not in pal:
                    pal.append(c)
                idx.append(pal.index(c))
            frames.append(idx)
    if len(pal) > 256:
        raise SystemExit("cort.h: %d colours, the 3DS table holds 255. Reduce the colours in the animation."
                         % (len(pal) - 1))
    if w != h:
        raise SystemExit("cort.h: the frames must be square, the atlas has %dx%d" % (w, h))
    maxf = max(r[2] for r in rows)
    out = ["// Cort, the mascot: square sprite frames and animations. "
           "Generated by assets/cort/make_cort.py. Do not edit.\n",
           "#pragma once\n",
           "// clang-format off\n",
           f"#define MASCOT_FRAME_SIZE {w} // sprite px, square\n",
           f"#define MASCOT_FRAME_COUNT {len(frames)}\n",
           f"#define MASCOT_ANIMATION_FRAMES_MAX {maxf}\n",
           "typedef struct {\n"
           "\tunsigned short firstFrame; // in MASCOT_FRAMES\n"
           "\tunsigned char frameCount;\n"
           "\tunsigned char loops;\n"
           "\tunsigned short frameMs[MASCOT_ANIMATION_FRAMES_MAX];\n"
           "} MascotAnimation;\n",
           "enum { " + ", ".join("ANIMATION_" + r[0].upper() for r in rows) + ", ANIMATION_COUNT };\n",
           "// 0xAARRGGBB; entry 0 is transparent.\n",
           "static const unsigned int MASCOT_PALETTE[] = {0, "
           + ", ".join("0x%02X%02X%02X%02X" % (c[3], c[0], c[1], c[2]) for c in pal[1:]) + "};\n",
           "static const MascotAnimation MASCOT_ANIMATIONS[ANIMATION_COUNT] = {\n"]
    for name, first, n, loop, ms in rows:
        out.append(f"\t{{{first}, {n}, {int(loop)}, {{{', '.join(map(str, ms))}}}}}, // {name}\n")
    out.append("};\n")
    out.append("static const unsigned char MASCOT_FRAMES[MASCOT_FRAME_COUNT]"
               "[MASCOT_FRAME_SIZE * MASCOT_FRAME_SIZE] = {\n")
    for f in frames:
        out.append("{" + ",".join(map(str, f)) + "},\n")
    out.append("};\n")
    out.append("// clang-format on\n")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("".join(out))


def main():
    strips, w, h = read_strips()
    write_header(strips, w, h)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
